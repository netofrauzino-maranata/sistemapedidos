-- Catálogo online por link: cada cliente tem um link próprio (link_token).
-- O cliente abre o link sem login, escolhe itens e quantidades e envia.
-- O envio vira um "pedido do catálogo" que o gestor (ou o vendedor do cliente)
-- revisa e transforma em pedido de venda. Nada aqui mexe em estoque.

alter table public.clientes
  add column link_token text unique default replace(gen_random_uuid()::text, '-', '');
update public.clientes set link_token = replace(gen_random_uuid()::text, '-', '') where link_token is null;
alter table public.clientes alter column link_token set not null;

create table public.pedidos_catalogo (
  id             uuid primary key default gen_random_uuid(),
  numero         bigint generated by default as identity unique,
  cliente_id     uuid not null references public.clientes(id),
  itens          jsonb not null,            -- [{produto_id, quantidade, preco}]
  total_estimado numeric(14,2) not null default 0,
  contato        text,
  observacao     text,
  status         text not null default 'nova' check (status in ('nova','aprovada','recusada')),
  pedido_id      uuid references public.pedidos(id),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);
create index pedidos_catalogo_status_idx on public.pedidos_catalogo (status, criado_em);
create trigger pedidos_catalogo_atualizado before update on public.pedidos_catalogo
  for each row execute function public.tg_atualizado_em();

alter table public.pedidos_catalogo enable row level security;
create policy pedidos_catalogo_select on public.pedidos_catalogo for select to authenticated
  using (public.eh_gestor() or (public.eh_usuario_ativo() and exists (
    select 1 from public.clientes c where c.id = cliente_id and c.vendedor_id = auth.uid())));
create policy pedidos_catalogo_update on public.pedidos_catalogo for update to authenticated
  using (public.eh_gestor() or (public.eh_usuario_ativo() and exists (
    select 1 from public.clientes c where c.id = cliente_id and c.vendedor_id = auth.uid())))
  with check (status in ('nova','aprovada','recusada'));

-- Catálogo público de um cliente (sem login). Não expõe custo nem estoque.
create or replace function public.catalogo_publico(p_token text)
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'cliente', coalesce(nullif(c.nome_fantasia, ''), c.razao_social),
    'empresa', (select jsonb_build_object('nome', coalesce(nullif(e.nome_fantasia, ''), e.razao_social),
                       'telefone', e.telefone, 'whatsapp', e.whatsapp) from public.empresa e where e.id = 1),
    'produtos', (
      select coalesce(jsonb_agg(jsonb_build_object(
               'id', p.id, 'codigo', p.codigo, 'nome', p.nome, 'unidade', p.unidade,
               'qtd_embalagem', p.qtd_embalagem, 'marca', p.marca, 'foto_url', p.foto_url,
               'categoria', cat.nome, 'preco', coalesce(ti.preco, p.preco_venda))
             order by cat.nome nulls last, p.nome), '[]'::jsonb)
      from public.produtos p
      left join public.categorias cat on cat.id = p.categoria_id and cat.ativo
      left join public.tabela_preco_itens ti on ti.produto_id = p.id and ti.tabela_id = c.tabela_preco_id and ti.ativo
        and exists (select 1 from public.tabelas_preco tp where tp.id = ti.tabela_id and tp.ativo)
      where p.ativo and p.mostrar_catalogo)
  )
  from public.clientes c
  where c.link_token = p_token and c.ativo and length(p_token) >= 20;
$$;

-- Cliente envia o que escolheu. Guarda o preço do momento só como referência.
create or replace function public.enviar_pedido_catalogo(p_token text, p_itens jsonb, p_contato text default null, p_observacao text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_cliente uuid;
  v_tabela  uuid;
  v_itens   jsonb;
  v_total   numeric;
  v_numero  bigint;
begin
  select id, tabela_preco_id into v_cliente, v_tabela
  from public.clientes where link_token = p_token and ativo and length(p_token) >= 20;
  if v_cliente is null then raise exception 'Link inválido ou desativado.'; end if;

  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 then raise exception 'Escolha pelo menos um produto.'; end if;
  if jsonb_array_length(p_itens) > 300 then raise exception 'Itens demais.'; end if;
  if (select count(*) from public.pedidos_catalogo where cliente_id = v_cliente and criado_em > now() - interval '1 hour') >= 10 then
    raise exception 'Muitos envios seguidos. Tente de novo mais tarde.';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object('produto_id', p.id, 'quantidade', x.qtd,
           'preco', coalesce(ti.preco, p.preco_venda)) order by x.ord), '[]'::jsonb),
         coalesce(sum(x.qtd * coalesce(ti.preco, p.preco_venda)), 0)
    into v_itens, v_total
  from (select (e->>'produto_id')::uuid as pid, (e->>'quantidade')::numeric as qtd, o as ord
        from jsonb_array_elements(p_itens) with ordinality as t(e, o)) x
  join public.produtos p on p.id = x.pid and p.ativo
  left join public.tabela_preco_itens ti on ti.produto_id = p.id and ti.tabela_id = v_tabela and ti.ativo
    and exists (select 1 from public.tabelas_preco tp where tp.id = ti.tabela_id and tp.ativo)
  where x.qtd > 0 and x.qtd <= 100000;

  if jsonb_array_length(v_itens) = 0 then raise exception 'Nenhum produto válido.'; end if;

  insert into public.pedidos_catalogo (cliente_id, itens, total_estimado, contato, observacao)
  values (v_cliente, v_itens, round(v_total, 2), left(nullif(trim(p_contato), ''), 120), left(nullif(trim(p_observacao), ''), 1000))
  returning numero into v_numero;
  return jsonb_build_object('numero', v_numero, 'itens', jsonb_array_length(v_itens), 'total', round(v_total, 2));
end $$;

-- Gera um link novo (o antigo para de funcionar). Respeita a RLS de clientes.
create or replace function public.novo_link_catalogo(p_cliente uuid)
returns text language sql security invoker set search_path = public as $$
  update public.clientes set link_token = replace(gen_random_uuid()::text, '-', '')
  where id = p_cliente returning link_token;
$$;

revoke all on function public.catalogo_publico(text) from public;
revoke all on function public.enviar_pedido_catalogo(text, jsonb, text, text) from public;
revoke all on function public.novo_link_catalogo(uuid) from public, anon;
grant execute on function public.catalogo_publico(text) to anon, authenticated;
grant execute on function public.enviar_pedido_catalogo(text, jsonb, text, text) to anon, authenticated;
grant execute on function public.novo_link_catalogo(uuid) to authenticated;
